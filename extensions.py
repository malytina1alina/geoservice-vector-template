# Собственная функция сервиса. Сервис вызывает extension() после основного расчёта и показывает её результат
# отдельным слоем карты и (или) таблицей. Функция использует только данные, которые сервис уже загрузил.
#
# Аргументы:
#   cells   – GeoDataFrame ячеек города (WGS 84): признаки окружения, «население», «объектов темы», «ожидаемое»,
#             «потенциал», «вне диапазона»; индекс – номер ячейки H3;
#   targets – GeoDataFrame объектов темы города;
#   city    – название города.
# Возвращает словарь:
#   {"name": "Название функции", "layer": GeoDataFrame или None, "column": "столбец слоя для раскраски" или None,
#    "table": DataFrame или None, "text": "краткий вывод" или None}

NAME = "Пример: ячейки с потенциалом больше 0,5"  # Название слоя и таблицы в интерфейсе.


def extension(cells, targets, city):
    """Пример: ячейки, где ожидается хотя бы на полобъекта больше, чем есть. Замените своей функцией."""
    layer = cells[cells["потенциал"] > 0.5][["потенциал", "население", "geometry"]]  # Ячейки с запасом спроса.
    return {"name": NAME, "layer": layer, "column": "потенциал", "table": None,  # Слой с раскраской и вывод.
            "text": f"{city}: ячеек с потенциалом больше 0,5 – {len(layer)}"}
