NAME = "Цветочные магазины в радиусе 1 км от мест-кандидатов"                           # Название функции в сервисе.
RADIUS_M = 1000                                                                 # 1 км – около 3 минут на автомобиле по городу: магазины, между которыми выбирает покупатель.


def extension(cells, targets, city):
    """Десять ячеек с наибольшим потенциалом и число объектов темы не дальше RADIUS_M от центра каждой."""
    utm = cells.estimate_utm_crs()                                              # Проекция UTM: расстояния в метрах.
    top = cells[~cells["вне диапазона"]].nlargest(10, "потенциал").to_crs(utm)  # Места-кандидаты.
    shops = targets.to_crs(utm)                                                 # Объекты темы в метрах.
    top["конкурентов в радиусе"] = [int((shops.distance(c) <= RADIUS_M).sum()) for c in top.centroid]  # Подсчёт.
    table = top[["потенциал", "конкурентов в радиусе"]].round(2).reset_index(drop=True)  # Таблица без геометрии.
    rivals = top["конкурентов в радиусе"]                                       # Конкуренты у каждого кандидата.
    return {"name": NAME, "layer": top.to_crs(4326)[["конкурентов в радиусе", "geometry"]],  # Результат функции для сервиса.
            "column": "конкурентов в радиусе", "table": table,
            "text": f"{city}: в радиусе {RADIUS_M} м от мест-кандидатов от {rivals.min()} до {rivals.max()} конкурентов"}

